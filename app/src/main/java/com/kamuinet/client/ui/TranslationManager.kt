    fun tr(key: String, vararg args: Pair<String, Any>): String {
        val table = translations[currentLang] ?: translations["en"]!!
        var text = table[key] ?: translations["en"]!![key] ?: key
        args.forEach { (k, v) ->
            text = text.replace("{$k}", v.toString())
        }
        return text
    }

